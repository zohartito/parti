using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using Xunit;

namespace Parti.Eval.V01;

/// <summary>
/// Emits docs/EVAL-v0.1.md with a per-fixture table. A fixture passes when every expectation
/// validates, including its expected terminal status (A14); the runtime status is a separate
/// column, so an expected error (25_error_repair_cap) is a pass and an unexpected clean finish is a
/// failure. The report carries no timings, so it is byte-stable across runs.
/// </summary>
public class EvalReporter
{
    [Fact]
    public async Task WriteReport()
    {
        var markdown = await BuildReportAsync();
        var outputPath = Path.Combine(FixtureLoader.RepoRoot(), "docs", "EVAL-v0.1.md");
        File.WriteAllText(outputPath, markdown);
    }

    /// <summary>Runs every gated fixture and renders the report.</summary>
    public static async Task<string> BuildReportAsync()
    {
        var rows = new List<ReportRow>();
        foreach (var path in FixtureLoader.DiscoverFixtureFiles())
        {
            rows.Add(await BuildRowAsync(path));
        }
        return BuildMarkdown(rows);
    }

    /// <summary>Loads, runs and classifies one fixture file. Load or run failures become rows.</summary>
    public static async Task<ReportRow> BuildRowAsync(string path)
    {
        EvalFixture fixture;
        try
        {
            fixture = FixtureLoader.Load(path);
        }
        catch (Exception ex)
        {
            return new ReportRow(Path.GetFileNameWithoutExtension(path), "(fixture failed to load)", "FAIL", $"load error: {ex.GetType().Name}", 0, 0, "load");
        }

        try
        {
            return Classify(await FixtureRunner.RunAsync(fixture));
        }
        catch (Exception ex)
        {
            return new ReportRow(fixture.Id, fixture.Description, "FAIL", $"crash: {ex.GetType().Name}", 0, 0, "crash");
        }
    }

    /// <summary>Classifies a finished run: pass means no predicate or invariant failed.</summary>
    public static ReportRow Classify(FixtureRunResult run)
    {
        var failures = PredicateEvaluator.Evaluate(run);
        return new ReportRow(
            run.Fixture.Id,
            run.Fixture.Description,
            failures.Count == 0 ? "pass" : "FAIL",
            $"{run.TerminalStatus} / {run.FinalReturn.Status}",
            run.ProviderCallCount,
            run.ToolDispatchCount,
            string.Join(", ", failures.Select(f => f.PredicateName).Distinct(StringComparer.Ordinal)));
    }

    /// <summary>Renders the markdown report. Deterministic for identical rows.</summary>
    public static string BuildMarkdown(IReadOnlyList<ReportRow> rows)
    {
        var sb = new StringBuilder();
        sb.Append("# Parti Eval v0.1\n");
        sb.Append('\n');
        sb.Append("Hermetic fixture results from `tests/Parti.Eval.v01/fixtures/`, run through the product loop\n");
        sb.Append("(`PartiComposition` → `ChatController`, streaming, three-pillar gate, lock and catalog policies,\n");
        sb.Append("strict declared arguments). Regenerated by `Parti.Eval.V01.EvalReporter.WriteReport` on every\n");
        sb.Append("test run; no timings, so the file is byte-stable. A fixture passes when all of its expectations\n");
        sb.Append("hold, including its expected terminal status; `runtime` is the controller status / final call\n");
        sb.Append("status the loop actually ended in. Live-model results are in `docs/EVAL-LIVE.md`.\n");
        sb.Append('\n');
        sb.Append($"Total fixtures: {rows.Count}\n");
        sb.Append($"Passing: {rows.Count(r => r.Result == "pass")}\n");
        sb.Append('\n');
        sb.Append("| id | description | result | runtime | provider calls | dispatched tools | failed predicates |\n");
        sb.Append("|----|-------------|--------|---------|----------------|------------------|-------------------|\n");
        foreach (var row in rows.OrderBy(r => r.Id, StringComparer.Ordinal))
        {
            sb.Append($"| {Cell(row.Id)} | {Cell(row.Description)} | {row.Result} | {Cell(row.Runtime)} | {row.ProviderCalls} | {row.DispatchedTools} | {Cell(row.FailedPredicates)} |\n");
        }
        return sb.ToString();
    }

    private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
}

/// <summary>One report row.</summary>
public sealed record ReportRow(
    string Id,
    string Description,
    string Result,
    string Runtime,
    int ProviderCalls,
    int DispatchedTools,
    string FailedPredicates);
